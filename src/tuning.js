/**
 * 「月初至今」查询的数据点秒数。取一天，每个指标约 31 个数据点。
 *
 * **实测（2026-08-22，ap-northeast-1）：这个粒度不存在「当天盲区」。** API 会为尚未结束
 * 的今天返回一个部分聚合的桶 —— 查询返回的最新桶起点就是今天 00:00 UTC，`sum` 是今天
 * 到此刻为止的量。所以「桶必须关闭后才可查」这条只适用于 300 秒那一档，不适用于这里。
 * `scheduled` 里那两条月度读数新鲜度告警仍然保留：零成本，而且能在 AWS 哪天改变这个
 * 行为时立刻响。
 *
 * 至于为什么不用 3600：只是数据点少、解析便宜而已。**不是**出于 CPU 预算 —— 线上实测
 * 每次触发的 CPU 时间 P50 1.68 ms、P99 2.57 ms（免费版上限 10 ms），余量充足。（拿本机的
 * `JSON.parse` 耗时去推断 Workers 运行时的开销没有意义，别这么估。）
 */
export const METRIC_PERIOD_SECONDS = 86400;

/**
 * 突发闸门的观察窗口与粒度：最近半小时，300 秒一个点。300 秒是 Lightsail 的原生上报
 * 粒度，取得再细也不会有更多信息。
 *
 * 窗口长度是被**稀释**和**落库延迟**两头夹出来的，不是随手取的整数：
 *
 * - 太长会稀释。速率是窗口内的平均值，所以一场刚开始 5 分钟的突发，在一小时的窗口里
 *   只显出真实速率的十二分之一。跳闸时的剩余余量（λ = 有效可见延迟）：
 *     `T >= W`（不再被稀释）：余量 = `H - λ`，与速率和窗口都无关；
 *     `T < W`（仍在稀释区）：余量 = `t_exh*H/(H+W-λ) - λ`。
 *   数值模拟验证过。W=60 分钟、5 Gbps 时余量是**负值**（配额烧完之后才跳闸），
 *   W=30 分钟约 +12 分钟 —— 这才是取 30 而不是 60 的实际依据。
 *
 *   推公式时**别忘了「月度用量读数本身也滞后 λ」这一项**：漏掉它会得到一个与速率无关的
 *   漂亮结论（「W=60 时还剩 7 分钟余量」），而数值模拟下六组算例全部对不上 —— 真实余量
 *   是负的，也就是把一次失败写成了「还有余量」。
 * - 太短会瞎。窗口整个落在落库延迟的阴影里就一个数据点都没有，闸门直接失效。W=20 分钟
 *   在延迟 20 分钟时归零；W=30 分钟即便延迟到 20 分钟仍有 2 个点。
 *
 * 30 分钟是这两条曲线的交点。**它只影响反应快慢，不影响灵敏度**——跳闸判据
 * `速率 > 剩余额度 / 视野` 里没有 W，所以缩短窗口不会让闸门更容易误报。
 *
 * 窗口必须是粒度的整数倍（`test/tuning.test.js` 钉住）。不是整数倍时，最后一个桶只覆盖
 * 不满 300 秒就被算进速率分母，速率会被报低 —— 而报低是唯一会让看门狗放行的方向。
 * `sumMetric` 按每个桶**实际覆盖的秒数**算分母，所以即便这条被破坏也不会失守 —— 但没有
 * 理由先把它破坏掉。
 */
export const BURST_WINDOW_SECONDS = 1800;
export const BURST_PERIOD_SECONDS = 300;

/**
 * 反应视野：按当前速率剩余额度撑不过这么久，就立刻停机，不等月度总量越过 THRESHOLD。
 *
 * **实测校正（2026-08-22）**：300 秒桶在**关闭那一刻就已经是终值**，不需要额外等待落库；
 * 尚未关闭的桶也会被返回（内容按约每分钟一档增长）。所以回路里「落库延迟」那一项在实测
 * 条件下接近零，真实回路约 16 分钟而不是按悲观值算的 26 分钟。参数不跟着调小 ——
 * 按悲观值定意味着真实余量更大，方向是安全的。
 *
 * 这个数必须覆盖一整个检测回路 —— 见下面 `DETECTION_LOOP_SECONDS`。按落库延迟 10 分钟
 * 算，回路是 26 分钟，取 60 分钟得到 2.3 倍余量。
 *
 * **改动 `CRON_INTERVAL_SECONDS` 时必须回来重新审视这个数。** cron 是回路里最大的一项：
 * 两分钟一次时回路只有 18 分钟，30 分钟的视野就够了；改成十分钟一次之后回路变成 26 分钟，
 * 同样的 30 分钟只剩 1.15 倍余量，而落库延迟一旦到 15 分钟就直接跌破 1.0 —— 额度会在
 * 闸门能动手之前烧完。
 *
 * 它同时是闸门唯一的灵敏度旋钮：跳闸判据等价于 `速率 > 剩余额度 / 视野`，所以调大它
 * 会线性地降低触发所需的速率。60 分钟意味着空表时要约 2.4 Gbps、用到 800 GiB 时约
 * 534 Mbps 才跳闸 —— 对一台个人站实例，这两个数仍然远在正常业务之上。想更保守就继续
 * 调大这个数（代价是可能掐掉一次合法的大流量传输），不要去动 `BURST_WINDOW_SECONDS`。
 */
export const REACTION_HORIZON_SECONDS = 3600;

/** 桶必须先关闭才可能被查到，最坏是一整个粒度。检测回路的第一项。 */
export const BUCKET_CLOSE_SECONDS = BURST_PERIOD_SECONDS;

/**
 * 指标落库延迟的设计取值，检测回路的第二项。
 *
 * **实测（2026-08-22，ap-northeast-1，5 次独立采样跨指标跨窗口）：约 0.9 分钟**，比这个
 * 悲观值快一个数量级。刻意**不**跟着调小 —— 一次采样不等于分布，而参数按悲观值定意味着
 * 真实情况下余量更大，方向是安全的。日志里的 `meter ... behind` 会持续校准它。
 */
export const ASSUMED_LAG_SECONDS = 600;

/** StopInstance 发出到真正断流。检测回路的第四项。 */
export const STOP_PROPAGATION_SECONDS = 60;

/**
 * 一整个检测回路：从「流量发生」到「实例真的断流」。反应视野必须覆盖它并留出余量，
 * `test/tuning.test.js` 要求至少 2 倍。
 */
export const DETECTION_LOOP_SECONDS =
  BUCKET_CLOSE_SECONDS + ASSUMED_LAG_SECONDS + CRON_INTERVAL_SECONDS + STOP_PROPAGATION_SECONDS;

/**
 * 指标落库延迟的容忍上限。超过它就报警 —— 此时突发闸门已经追不上一场满速突发了。
 *
 * **这个数是从检测回路推出来的，不是从观察窗口推出来的。** 两者管的是不同的事：窗口管
 * 分辨率（够不够几个数据点算速率），回路管及时性（跳闸时还剩多少额度）。
 *
 * 推导用的是和视野同一条规则 —— 回路必须留在视野的一半以内（即 2 倍余量）：回路里除
 * 延迟之外的固定部分是 桶关闭 300 + cron 600 + 停机生效 60 = 960 秒，于是延迟上限是
 * 3600/2 − 960 = 840 秒。取 12 分钟，比这个上限再早一点，也比「5 Gbps 下真的守不住」
 * 的经验临界点（16 分钟）早四分钟。`test/tuning.test.js` 会把这条关系钉住。
 *
 * **不要把它挂回观察窗口上**（例如 `BURST_WINDOW_SECONDS - 2 * BURST_PERIOD_SECONDS`）。
 * 那样写在 cron 两分钟一次时看起来没问题：临界点 25 分钟，20 分钟的告警是提前的。但 cron
 * 放宽到十分钟之后临界点降到 16 分钟，同一个 20 分钟就成了**迟到四分钟**的告警 —— 延迟
 * 落在 [16, 20) 分钟这一段时，设计已经失效而日志里没有任何提示。窗口管分辨率、回路管
 * 及时性，两者会在改 cron 时朝不同方向走。
 */
export const MAX_TOLERABLE_LAG_SECONDS = 720;

