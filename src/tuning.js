// 三、上游响应的可信边界
// ─────────────────────────────────────────────────────────────────────────────

/**
 * 向 GetInstanceMetricData 请求的单位，同时也是校验返回数据点所用的期望值。
 *
 * **一个常量供两处使用是有意的。** 实测（2026-08-22，ap-northeast-1）：`unit` 传成
 * `Bits` / `Count` / `Percent` / `Seconds` / `Megabytes` 中的任意一个，AWS 都回
 * **HTTP 200、`metricName` 正确回显、`metricData` 是空数组** —— 没有任何一处报错。
 * 于是 `sumMetric` 的双信号校验完全放行，用量读成干净的 0 字节，而 0 是唯一会让看门狗
 * 什么都不做的读数：静态线永不越线、突发闸门无数据可算，实例一路烧到超额。
 *
 * 请求侧和校验侧共用同一个常量，就不可能出现「改了请求忘了校验」；而返回的数据点确实
 * 带 `unit` 字段（实测形状 `{"sum":785943,"timestamp":1787405700,"unit":"Bytes"}`），所以
 * 「AWS 哪天改了返回单位」这一侧也有实打实的检查，而不是靠假设。
 *
 * 至于「请求的单位不对导致空响应」，响应本身分辨不了 —— 它和「实例没在跑」长得一模一样。
 * 那一侧由 `scheduled` 里的零读数告警承接：实例状态是 running 而读数为零，物理上不成立。
 */
export const METRIC_UNIT = "Bytes";

/**
 * 时间戳与查询终点之间允许的最大偏离，超过就当这个时间戳不可用。
 *
 * 防的是「是数字，但量级错了」—— 例如毫秒而不是 Unix 秒。
 *
 * **只检查 `typeof === "number"` 是不够的**：毫秒时间戳会让 `endTime − (newest + 300)`
 * 变成一个巨大的负数，被 `Math.max(0, …)` 钳到 0，于是**新鲜度检测整体失效，而日志还
 * 宣称数据很新鲜**。这属于最难发现的一类故障：读数存在，但语义是错的。
 *
 * 取 400 天：比最长的查询窗口（一个月）宽得多，也覆盖了 3600 秒粒度 455 天的保留期，
 * 不会误伤任何真实时间戳；而毫秒时间戳会偏离约五万年，隔着几个数量级。
 */
export const MAX_TIMESTAMP_SKEW_SECONDS = 400 * 86400;

/**
 * 一个 GiB 的字节数（2^30）。整套单位体系都以它为基准，与 Lightsail `GetBundles` 返回的
 * `transferPerMonthInGb` 对齐：该字段把「1 TB」记为 1024，同一响应里的 `ramSizeInGb: 0.5`
 * 也只可能是 512 MiB，两处一致地指向 GiB。于是 QUOTA_GIB 可以直接填那个数字。
 */
export const BYTES_PER_GIB = 1024 ** 3;

/**
 * QUOTA_GIB 的上界。
 *
 * 不是随手定的：超过它之后 `quotaGib * BYTES_PER_GIB` 就落到 Number 的安全整数范围之外，
 * 字节比较开始丢精度；再大一点直接溢出成 Infinity，于是停机线变成一个永远够不到的数 ——
 * 一个看起来在跑、实际上什么都不做的看门狗。这正是 THRESHOLD 那条上界要防的东西。
 *
 * 8 PiB/月大约是 Lightsail 最大套餐的四千倍，不会误伤任何真实配置。
 */
export const MAX_QUOTA_GIB = Number.MAX_SAFE_INTEGER / BYTES_PER_GIB;

/**
 * 月度读数允许落后的时长上限，超过就报「今天的流量对静态线不可见」。
 *
 * 挂在突发粒度的两倍上：月度桶是一整天，但判据问的是「最新的桶结束多久了」，而一个
 * 已经结束的天桶应当立刻可查。留两个突发粒度是给时钟偏差和落库抖动的余地。
 */
export const MONTH_BEHIND_TOLERANCE_SECONDS = 2 * BURST_PERIOD_SECONDS;

/**
 * 月初之后多久，「月初至今恰为零」才值得报警。
 *
 * 月份刚开始的头几分钟，一台正常运行的实例确实可能还没有任何数据点（当天那个桶要等
 * 约一分钟才会出现）。两小时远远越过这个不确定区，又足够早 —— 一条坏掉的指标管道会在
 * 当月第一次触发之后的两小时内被喊出来，此后每一次触发都喊。
 */
export const ZERO_READING_GRACE_SECONDS = 2 * 3600;

/**
 * 单次 GetInstanceMetricData 能返回的数据点上限。
 *
 * 上限本身两次实测都是 1440（恰好请求 1440 个点拿回 1440 个）。**超限之后的表现，两次
 * 实测不一致**：
 *
 * - **2026-08-22（ap-northeast-1）**：超限不报错 —— 1441 / 2880 个点都拿回 **0 个**，
 *   HTTP 仍是 200、`metricName` 照常回显。这是「读数存在、语义全错」那一类，而且恰好
 *   落在唯一会让看门狗什么都不做的值上。
 * - **2026-08-30（ap-northeast-1）**：同样的构造一律是 HTTP 400 `InvalidInputException`，
 *   错误消息明说 "requested number of datapoints exceeds the limit of 1,440"（1441 /
 *   2880 × period 300、2976 × period 900 都试过）。
 *
 * 两条记录必有一条不反映当时上游的真实行为，且 08-22 已无法复现。守卫按「两种形态都可能
 * 出现」设计：在发请求之前就抛错 —— 400 的形态下省一次往返，静默空的形态下这道守卫是
 * 唯一防线。sumMetric 里那道检查的完整推导见其注释。
 *
 * 本项目两个查询离上限都很远（月度 31 个点、突发 6 个），所以这个检查平时不会响。它防的
 * 是**调参**：把 METRIC_PERIOD_SECONDS 从 86400 改成 900，月度查询就要 2976 个点 ——
 * 按 08-30 的行为每轮以 400 响亮失败，按 08-22 的记录则是每轮静默读到 0 字节。两种形态
 * 下守卫都在第一次触发时拦下。
 */
export const MAX_DATAPOINTS_PER_QUERY = 1440;

/**
 * 查询窗口的最小宽度。新月份的第一次触发里 `startTime` 和 `endTime` 会重合，而宽度为零
 * 的区间会被 API 拒绝。
 */
export const MIN_WINDOW_SECONDS = 60;

