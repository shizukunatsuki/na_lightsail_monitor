/**
 * 全部调参常量集中在这里。
 *
 * 分散的调参是这个项目真实踩过的坑：cron 间隔写在 `wrangler.jsonc`、反应视野写在
 * `src/index.js` 顶部、延迟容忍上限的推导写在 `test/tuning.test.js` 里，而这三个数是
 * 互相约束的。cron 从两分钟放宽到十分钟那次，只有 cron 被改了，于是延迟告警从「提前
 * 五分钟」悄悄变成「迟到四分钟」—— 代码照跑、测试照绿，防线薄了没人知道。
 *
 * 还有一类更隐蔽的分散：数值直接内联在用它的那一行里（`2 * 3600` 的零读数宽限、
 * `retries: 2`、`Number.MAX_SAFE_INTEGER / BYTES_PER_GIB` 的配额上界）。它们同样是决策，
 * 只是没有名字，于是既不会被复核也不会被测试引用。现在一律有名字、有出处、集中在这一份。
 *
 * 唯一不在这里的是**部署侧变量**（区域、实例名、配额、阈值、MANUAL_HOLD）：它们逐个部署
 * 不同，属于 `wrangler.jsonc` 的 `vars`，由 `readConfig` 校验。cron 也只能住在
 * `wrangler.jsonc` 里，所以这里留一份**声明**，并由 `test/tuning.test.js` 与真身核对。
 */

