/**
 * cron 触发间隔，秒。**真身在 `wrangler.jsonc` 的 `triggers.crons` 里**，这里是一份供
 * 推导使用的声明；`test/tuning.test.js` 会读那个文件核对两者一致，改了一边忘了另一边
 * 会直接测试失败。
 *
 * 它是检测回路里最大的一项，因此下面几乎每一个视野／门槛都由它推出来。十分钟一次、
 * 一天 144 次，每天约 720 次 AWS 调用。更低的频率不是出于额度（Workers 免费版每天
 * 10 万次请求，Lightsail API 不计费也不限速），而是不希望高频轮询被上游判定为滥用接口。
 */
export const CRON_INTERVAL_SECONDS = 600;

